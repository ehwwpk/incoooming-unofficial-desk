def build_call_history() -> tuple[CallSaleRecord, ...]:
    return tuple(_record(item) for item in CALL_FIXTURES)


def _record(item: CallFixture) -> CallSaleRecord:
    underlying = D(item.underlying_at_sale)
    strike = D(item.strike)
    premium = D(item.premium_per_share)
    gross_premium = premium * item.contracts * 100
    buyback = D(item.buyback_cost)
    return CallSaleRecord(
        record_id=item.record_id,
        campaign_id=item.campaign_id,
        parent_record_id=item.parent_record_id,
        policy_id=item.policy_id,
        symbol=item.symbol,
        sold_on=item.sold_on,
        expires_on=item.expires_on,
        contracts=item.contracts,
        underlying_at_sale=underlying,
        strike=strike,
        strike_upside_percent=((strike / underlying - 1) * 100).quantize(CENT),
        days_to_expiration=(item.expires_on - item.sold_on).days,
        premium_per_share=premium,
        gross_premium=gross_premium,
        buyback_cost=buyback,
        net_cash=gross_premium - buyback,
        outcome=item.outcome,
        sale_signal=item.sale_signal,
        closed_on=item.closed_on,
        fees=D(item.fees),
    )
