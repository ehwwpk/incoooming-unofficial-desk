def _record(
    symbol: str,
    sold_on: date,
    expires_on: date,
    contracts: int,
    underlying: str,
    strike: str,
    premium: str,
    buyback_cost: str,
    outcome: str,
    signal: str,
) -> CallSaleRecord:
    underlying_value = D(underlying)
    strike_value = D(strike)
    premium_value = D(premium)
    gross_premium = premium_value * contracts * 100
    buyback_value = D(buyback_cost)
    return CallSaleRecord(
        symbol=symbol,
        sold_on=sold_on,
        expires_on=expires_on,
        contracts=contracts,
        underlying_at_sale=underlying_value,
        strike=strike_value,
        strike_upside_percent=((strike_value / underlying_value - 1) * 100).quantize(CENT),
        days_to_expiration=(expires_on - sold_on).days,
        premium_per_share=premium_value,
        gross_premium=gross_premium,
        buyback_cost=buyback_value,
        net_cash=gross_premium - buyback_value,
        outcome=outcome,
        sale_signal=signal,
    )
